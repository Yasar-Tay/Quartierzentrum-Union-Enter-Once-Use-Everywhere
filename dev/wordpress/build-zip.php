<?php

/**
 * Builds dist/enter-once-sync.zip (run through bin/build-zip, inside Docker, project at /app).
 *
 *  - plugin files: enter-once-sync.php, src/Core, src/WordPress, languages, readme.txt, LICENSE
 *  - the German guides: docs/de/*.md
 *  - production dependencies: sabre/vobject, sabre/xml, sabre/uri, with their namespace prefixed
 *    to EnterOnce\Vendor\Sabre (A-13), so another plugin's copy of sabre cannot collide
 *  - a small PSR-4 autoloader instead of Composer's (no dev dependencies, no Composer at runtime)
 *  - the widget files the embed snippet loads: widget/enteronce-widget.js and .css
 * Afterwards the built copy is checked: every PHP file lints, and the prefixed core reads the
 * sample calendar to 71 occurrences.
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 */

declare(strict_types=1);

const PREFIX = 'EnterOnce\\Vendor\\';

$root = '/app';
$build = sys_get_temp_dir() . '/eo-build';
$plugin = $build . '/enter-once-sync';
$zipPath = $root . '/dist/enter-once-sync.zip';

function rrmdir(string $dir): void
{
    if (!is_dir($dir)) {
        return;
    }
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
    foreach ($it as $f) {
        $f->isDir() ? rmdir($f->getPathname()) : unlink($f->getPathname());
    }
    rmdir($dir);
}

function copyTree(string $from, string $to, array $skip = []): void
{
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($from, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::SELF_FIRST);
    foreach ($it as $f) {
        $rel = substr($f->getPathname(), strlen($from) + 1);
        foreach ($skip as $pattern) {
            if (fnmatch($pattern, $rel)) {
                continue 2;
            }
        }
        $dest = $to . '/' . $rel;
        if ($f->isDir()) {
            @mkdir($dest, 0775, true);
        } else {
            @mkdir(dirname($dest), 0775, true);
            copy($f->getPathname(), $dest);
        }
    }
}

function prefixFile(string $path): void
{
    $code = (string) file_get_contents($path);
    // "Sabre\" not preceded by a word character: namespace, use, \Sabre\…, and class names in strings.
    $new = (string) preg_replace('/(?<![\w])Sabre\\\\/', str_replace('\\', '\\\\', PREFIX) . 'Sabre\\\\', $code);
    if ($new !== $code) {
        file_put_contents($path, $new);
    }
}

rrmdir($build);
mkdir($plugin, 0775, true);

copy($root . '/enter-once-sync.php', $plugin . '/enter-once-sync.php');
copy($root . '/uninstall.php', $plugin . '/uninstall.php');
copyTree($root . '/src/Core', $plugin . '/src/Core');
copyTree($root . '/src/WordPress', $plugin . '/src/WordPress');
if (is_dir($root . '/languages')) {
    copyTree($root . '/languages', $plugin . '/languages');
}
@mkdir($plugin . '/widget', 0775, true);
foreach (['enteronce-widget.js', 'enteronce-widget.css'] as $f) {
    if (!is_file($root . '/widget/' . $f)) {
        fwrite(STDERR, "Missing widget/$f\n");
        exit(1);
    }
    copy($root . '/widget/' . $f, $plugin . '/widget/' . $f);
}
foreach (['vobject', 'xml', 'uri'] as $pkg) {
    copyTree($root . '/vendor/sabre/' . $pkg, $plugin . '/vendor/sabre/' . $pkg, ['bin', 'bin/*', 'tests', 'tests/*', '.github', '.github/*', '*.md', 'phpunit*', '.php-cs-fixer*', 'phpstan*']);
}

// Prefix sabre's namespace everywhere it appears.
$php = new RegexIterator(new RecursiveIteratorIterator(new RecursiveDirectoryIterator($plugin, FilesystemIterator::SKIP_DOTS)), '/\.php$/');
foreach ($php as $f) {
    prefixFile($f->getPathname());
}

file_put_contents($plugin . '/vendor/autoload.php', <<<'PHP'
<?php
/** Autoloader of the built plugin (no Composer at runtime). Generated by bin/build-zip. */
spl_autoload_register(static function (string $class): void {
    static $map = [
        'EnterOnce\\Vendor\\Sabre\\VObject\\' => '/sabre/vobject/lib/',
        'EnterOnce\\Vendor\\Sabre\\Xml\\' => '/sabre/xml/lib/',
        'EnterOnce\\Vendor\\Sabre\\Uri\\' => '/sabre/uri/lib/',
        'EnterOnce\\' => '/../src/',
    ];
    foreach ($map as $prefix => $dir) {
        if (strncmp($class, $prefix, strlen($prefix)) === 0) {
            $file = __DIR__ . $dir . str_replace('\\', '/', substr($class, strlen($prefix))) . '.php';
            if (is_file($file)) {
                require $file;
            }

            return;
        }
    }
});
require_once __DIR__ . '/sabre/uri/lib/functions.php';
require_once __DIR__ . '/sabre/xml/lib/Deserializer/functions.php';
require_once __DIR__ . '/sabre/xml/lib/Serializer/functions.php';
PHP);

// readme.txt and LICENSE from the plugin root, and the German guides.
foreach (['readme.txt', 'LICENSE'] as $f) {
    if (!is_file($root . '/' . $f)) {
        fwrite(STDERR, "Missing $f\n");
        exit(1);
    }
    copy($root . '/' . $f, $plugin . '/' . $f);
}
$guides = glob($root . '/docs/de/*.md') ?: [];
if ($guides === []) {
    fwrite(STDERR, "Missing docs/de/*.md\n");
    exit(1);
}
@mkdir($plugin . '/docs/de', 0775, true);
foreach ($guides as $g) {
    copy($g, $plugin . '/docs/de/' . basename($g));
}
$version = '0.1.0';
if (preg_match('/^\s*\*\s*Version:\s*(\S+)/m', (string) file_get_contents($root . '/enter-once-sync.php'), $m)) {
    $version = $m[1];
}
if (!preg_match('/^Stable tag:\s*' . preg_quote($version, '/') . '\s*$/m', (string) file_get_contents($root . '/readme.txt'))) {
    fwrite(STDERR, "readme.txt: Stable tag does not match the plugin version $version\n");
    exit(1);
}

// Checks on the built copy.
$failed = 0;
foreach (new RegexIterator(new RecursiveIteratorIterator(new RecursiveDirectoryIterator($plugin, FilesystemIterator::SKIP_DOTS)), '/\.php$/') as $f) {
    exec('php -l ' . escapeshellarg($f->getPathname()) . ' 2>&1', $out, $code);
    if ($code !== 0) {
        fwrite(STDERR, implode("\n", $out) . "\n");
        ++$failed;
    }
    $out = [];
}
if ($failed > 0) {
    fwrite(STDERR, "$failed files do not lint\n");
    exit(1);
}
$check = <<<'PHP'
require $argv[1] . '/vendor/autoload.php';
if (class_exists('Sabre\\VObject\\Reader', false)) { fwrite(STDERR, "unprefixed sabre loaded\n"); exit(1); }
$core = new EnterOnce\Core\Core([], 'union');
$r = $core->read(file_get_contents($argv[2]), new DateTimeImmutable('2026-11-19 00:00', new DateTimeZone('Europe/Zurich')), EnterOnce\Core\Window::fromDates('2026-11-19', '2027-03-31'));
$n = count($r->activeOccurrences());
if ($n !== 71 || !class_exists('EnterOnce\\Vendor\\Sabre\\VObject\\Reader', false)) { fwrite(STDERR, "smoke test failed: $n\n"); exit(1); }
echo "smoke test: 71 occurrences with the prefixed library\n";
PHP;
passthru('php -r ' . escapeshellarg($check) . ' ' . escapeshellarg($plugin) . ' ' . escapeshellarg($root . '/tests/fixtures/union-beispielkalender.ics'), $code);
if ($code !== 0) {
    exit(1);
}
if (preg_match_all('/(?<![\w\\\\])Sabre\\\\(?!\\\\)/', implode("\n", array_map('file_get_contents', glob($plugin . '/src/Core/*.php'))), $mm) > 0) {
    fwrite(STDERR, "unprefixed reference left in src/Core\n");
    exit(1);
}

@mkdir(dirname($zipPath), 0775, true);
@unlink($zipPath);
$zip = new ZipArchive();
if ($zip->open($zipPath, ZipArchive::CREATE) !== true) {
    fwrite(STDERR, "cannot create $zipPath\n");
    exit(1);
}
$files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($plugin, FilesystemIterator::SKIP_DOTS));
$count = 0;
foreach ($files as $f) {
    $zip->addFile($f->getPathname(), 'enter-once-sync/' . str_replace('\\', '/', substr($f->getPathname(), strlen($plugin) + 1)));
    ++$count;
}
$zip->close();
rrmdir($build);
printf("Built dist/enter-once-sync.zip (%d files, %d KB, version %s)\n", $count, (int) (filesize($zipPath) / 1024), $version);
